export function getAllCallRecords() {
  return CALL_RECORDS;
}

export function getCallRecord(callId) {
  return CALL_RECORDS.find((r) => r.call_id === callId) || null;
}

export function getCallAnalysis(callId) {
  return CALL_ANALYSIS[callId] || null;
}

export function getDashboardStats(records = CALL_RECORDS) {
  const total = records.length;
  const avgQa = Math.round((records.reduce((s, r) => s + r.qa_score, 0) / total) * 100);
  const escalations = records.filter((r) => r.escalation_flag).length;
  const negativeSentiment = records.filter((r) => r.sentiment === 'Negative').length;
  const guardrailRisk = records.filter((r) => r.guardrail_risk === 'High' || r.guardrail_risk === 'Medium').length;
  return { total, avgQa, escalations, negativeSentiment, guardrailRisk };
}
